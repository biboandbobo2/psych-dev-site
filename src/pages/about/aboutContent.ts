/**
 * Базовый контент для страницы «О нас» (/about).
 * Та же структура используется как fallback и как источник для `pages/about`.
 * Контент партнёров вынесен отдельно — см. partnersContent.ts.
 */

export interface AboutTabBase {
  id: string;
  label: string;
}

export interface AboutTextSection {
  heading?: string;
  paragraphs: string[];
}

export interface AboutPlaceholderTab extends AboutTabBase {
  kind: 'placeholder';
  intro: string;
  note?: string;
}

export interface AboutTextTab extends AboutTabBase {
  kind: 'text';
  intro?: string;
  sections: AboutTextSection[];
}

export interface AboutOfflineTab extends AboutTabBase {
  kind: 'offline';
  intro: string;
  paragraphs: string[];
  instagramUrl: string;
  bookingPath: string;
  bookingLabel: string;
  instagramLabel: string;
}

export interface AboutPartnersTab extends AboutTabBase {
  kind: 'partners';
  intro: string;
}

/**
 * Системная вкладка: список карточек проектов академии.
 * Контент собирается автоматически из `projectPages/*` + статического каталога,
 * через UI редактора напрямую не редактируется (только intro над списком).
 */
export interface AboutProjectsTab extends AboutTabBase {
  kind: 'projects';
  intro: string;
  sections?: AboutTextSection[];
}

export type AboutTab =
  | AboutTextTab
  | AboutPlaceholderTab
  | AboutOfflineTab
  | AboutPartnersTab
  | AboutProjectsTab;


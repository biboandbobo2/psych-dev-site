def part3():
    """Такты 80–99, фа мажор, тик-так: wood block четвертями, пиццикато «маршем», маримба восьмыми.
    Заставка: флейта начинает тему. «Козырёк»: фраза вслух (кларнет + флейта) → козырьки вниз, фактура редеет →
    та же фраза шёпотом у одной челесты (шепчет Дима) → козырьки вверх, фраза снова вслух → шёпот повторяет Миша
    (челеста) → вывод тёплым кларнетом. «Шахматы»: перекличка флейты (Дима) и кларнета (папа), стоп-кадр
    «Угадайте» держит аккорд; каданс E7 → ля мажор."""
    c, h, chs = START['ch3'], START['helmet'], START['chess']
    z0, z1 = at('chess', 4.2), at('chess', 6.1)                  # стоп-кадр «Угадайте»

    def groove(t0, t1, vel=36):
        arp('mar', t0, t1, [0, 1, 2, 1], E, vel, 60, 77, art=.5)
        bassline('pizz', t0, t1, 'march', vel + 12, lo=43)
    seq('fl', T(c), "C6/2 D6/1 C6/1 A5/2 C6/1 A5/1 | G5/2 A5/2 F5/4", E, 64)
    arp('harp', T(c), T(h), [0, 1, 2, 3, 4, 3, 2, 1], E, 30, 53, 81, art=1.4)
    bassline('pizz', T(c), T(h), 'root', 42, lo=43)
    dpat(c, c + 1, TICKTOCK, .7)
    # «Козырёк»: вслух
    dpat(h, h + 1, TICKTOCK, .9)
    groove(T(h), T(h + 2, 1), 32)
    pad('str', T(c), T(h + 2), 32, 53, 72)
    phrase = "C5/1 D5/1 C5/1 A4/1 C5/1 A4/1 G4/2"
    for tt, d, pp in seq('cl', T(h + 1), phrase, E, 58):
        put('fl', tt, d, pp + 12, 40)
    # козырьки вниз: фактура редеет; шёпот Димы — одна челеста, тиканье секундомера едва слышно
    dpat(h + 2, h + 3, {WBH: ('x...x...', 14), WBL: ('..x...x.', 12)})
    arp('mar', T(h + 2, 1), T(h + 2, 3), [0, 1, 2, 1], E, 26, 60, 77, art=.5)
    bassline('pizz', T(h + 2, 1), T(h + 4, 2), 'root', 36, lo=43)
    pad('str', T(h + 2), T(h + 4, 2), 38, 53, 72)
    seq('cel', T(h + 2, 3.5), octave(phrase, 1) + " A5/2", E, 54)
    # козырьки вверх — снова вслух
    for tt, d, pp in seq('cl', T(h + 4, 2), "C5/1 D5/1 C5/1 A4/1 | C5/1 A4/1 G4/1 A4/1 F4/4", E, 62):
        if tt < T(h + 5, 2):
            put('fl', tt, d, pp + 12, 44)
    ticks(T(h + 4, 2), T(h + 6), .9)
    groove(T(h + 4, 2), T(h + 6, 2), 34)
    pad('str', T(h + 4, 2), T(chs), 32, 53, 72)
    seq('ob', T(h + 6), "Bb4/4 A4/4", E, 52)
    # Миша сам шепчет — снова одна челеста, фактура тише
    bassline('pizz', T(h + 6, 2), T(h + 8), 'root', 36, lo=43)
    dpat(h + 6, h + 7, {WBH: ('x...x...', 14), WBL: ('..x...x.', 12)})
    seq('cel', T(h + 6, 3.5), octave(phrase, 1) + " A5/2", E, 52)
    # вывод: тёплый кларнет, тиканье возвращается
    dpat(h + 8, chs, TICKTOCK, .8)
    groove(T(h + 8), z0, 32)
    seq('cl', T(h + 8), "D5/1 F5/1 D5/1 Bb4/1 D5/1 Bb4/1 G4/2 | A4/4 G4/4", E, 58)
    # «Шахматы»: перекличка; стоп-кадр — тиканье и пульс замирают, аккорд держится
    ticks(T(chs + 1), z0, .9)
    pad('str', T(chs), z0, 32, 53, 72)
    pad('str', z0, z1, 40, 53, 74)
    hold(z0, z1, (('vib', 74), ('harp', 70)), 34)
    ticks(T(chs + 2, 2), T(chs + 7), .9)
    groove(T(chs + 2, 2), T(chs + 8), 32)
    pad('str', z1, T(chs + 8), 32, 53, 72)
    seq('fl', T(chs), "C6/1 D6/1 C6/1 A5/1 F5/4", E, 64)
    seq('cl', T(chs + 1), "C5/1 D5/1 C5/1 A4/1 F4/3", E, 62)
    seq('fl', T(chs + 3), "A5/1 Bb5/1 A5/1 F5/1 A5/4", E, 64)
    seq('cl', T(chs + 4), "F4/1 G4/1 F4/1 D4/1 F4/2 D4/2", E, 60)
    seq('fl', T(chs + 5), "Bb5/2 G5/2 C6/2 E5/2", E, 60)
    seq('cl', T(chs + 6), "A4/2 C5/2 D5/2 F5/2 | D5/4 B4/4", E, 58)
    seq('fl', T(chs + 7), "F#5/4 E5/2 G#5/2", E, 58)
    gliss('harp', T(chs + 7, 3.2), 57, 81, 30, 36, 'A')



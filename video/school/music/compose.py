def at(name, s):
    """Тик момента s секунд от начала сцены (для стоп-кадров не на тактовой черте)."""
    return int(round((START[name] - 1) * BAR + s * SEC))


def ticks(t0, t1, scale=1.0):
    """Тик-так четвертями (как TICKTOCK) на отрезке [t0, t1) — для стоп-кадра внутри такта."""
    for k in range(-(-t0 // Q), (t1 - 1) // Q + 1):
        hi = (k % 4) in (0, 2)
        put('dr', k * Q, Q * 0.4, WBH if hi else WBL, (24 if hi else 20) * scale, 9, jit=4)


def full(t0, t1):
    """Номера тактов, целиком лежащих в [t0, t1) (для ударных: не заходить в стоп-кадр)."""
    return -(-t0 // BAR) + 1, t1 // BAR


